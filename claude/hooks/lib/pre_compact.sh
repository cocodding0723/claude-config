#!/usr/bin/env bash
# 표준 출력은 압축 요약 지시로 사용되므로 기능 허브에서만 출력.
cwd=$(jq -r '.cwd // empty | select(type == "string")' 2>/dev/null) || exit 0
case "$(basename "$cwd")" in coord-feat-?*-hub) ;; *) exit 0 ;; esac
cat <<'EOF'
기능 허브의 압축 요약에는 다음 정보와 확인된 상태만 남긴다.
- 기능 카드 id와 현재 단계. 카드 코멘트·작업 스레드가 상세 기록의 정본이다.
- 대기 중인 결정 id, 승인 여부와 승인 범위. 확인하지 못한 답은 승인으로 추정하지 않는다.
- 맡긴 작업자와 카드 id, 진행 중인 작업과 남은 확인 항목.
- 사용자 원문 지시 번호별 처리 상태와 미처리 항목. 지시의 의미·제약·승인 근거는 보존한다.
도구 출력 원문, 파일 덤프, 반복 로그는 버리고 카드·증거 파일 경로와 판정만 남긴다.
압축 후에는 새로 주입된 카드 상태·단계별 다음 할 일을 확인하고 진행 기록은 bd comments add <카드>에 남긴다.
EOF
exit 0
